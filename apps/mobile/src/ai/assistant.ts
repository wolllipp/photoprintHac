/**
 * Заглушка ассистента клиента (роль «клиент»).
 * В продукте: POST /claims (фото дефекта → проверка на типовые признаки брака) и assistant_answer
 * на локальной LLM с инструментами только этой роли (notes/07-architecture.md, раздел 6).
 */
export type ClaimVerdict = {
  defect: 'stripe' | 'shift' | 'crop' | 'color';
  label: string;
  decision: 'reprint';
  eta: string;
};

/** «Проверка» фото дефекта: в демо всегда полоса печати → перепечатка без возврата. */
export async function checkDefect(): Promise<ClaimVerdict> {
  await new Promise((r) => setTimeout(r, 1800));
  return { defect: 'stripe', label: 'полоса появилась при печати', decision: 'reprint', eta: '≈ 19 ноября' };
}

/** Короткие ответы на частые вопросы — из справочника D14, без доступа к данным компании. */
export function quickAnswer(q: string): string {
  if (/когда|приед/i.test(q)) return 'Новая книга уйдёт в печать сегодня. Европочта привезёт её в ваш пункт ≈ 19 ноября — пришлю уведомление.';
  if (/челов|оператор/i.test(q)) return 'Передал разговор сотруднику поддержки. Ответят в течение 15 минут — с 9:00 до 21:00 каждый день.';
  if (/выручк|компан|сотрудник|зарплат/i.test(q)) return 'Я помогаю с вашими заказами и книгами. Данных компании у меня нет.';
  return 'Могу помочь со статусом заказа, сроками, доставкой и браком. Что случилось?';
}
